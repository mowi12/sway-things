//! kanshi as the display backend: where its files are, whether it is installed, whether its
//! config includes ours, and writing ours.
//!
//! Our profiles go into `$XDG_CONFIG_HOME/kanshi/sway-things.conf`. The user's kanshi config
//! (`$XDG_CONFIG_HOME/kanshi/config`) only needs `include` of that file; it is never written,
//! except that it is created with that line when there is none at all. Nothing here runs a
//! shell: kanshi and kanshictl are started with argument lists.

use std::io;
use std::path::{Path, PathBuf};
use std::time::Duration;

use super::profiles::{Profiles, kanshi_config};
use super::workspaces::Placing;
use crate::atomic;
use crate::i18n::Text;
use crate::msg;
use crate::state::xdg_dir;
use crate::sway_config::SwayConfig;

/// The first line of the files Sway Things writes for kanshi.
const HEADER: &str = "# Generated by Sway Things";

/// In the displays of a profile of [`user_profiles`]: one display, whichever (`output *`).
pub const ONE: &str = "*";
/// In the displays of a profile of [`user_profiles`]: any number of displays, whichever
/// (`...output *`).
pub const ANY: &str = "...*";

/// kanshi's files for this user.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct KanshiFiles {
    /// The user's kanshi config, which includes ours.
    pub config: PathBuf,
    /// Ours, with the profiles.
    pub ours: PathBuf,
}

impl KanshiFiles {
    /// The files in `$XDG_CONFIG_HOME/kanshi`, or `~/.config/kanshi`. `None` without either.
    pub fn from_env() -> Option<Self> {
        let config_home = xdg_dir(
            std::env::var_os("XDG_CONFIG_HOME"),
            std::env::var_os("HOME"),
            ".config",
        )?;
        Some(Self::in_dir(&config_home.join("kanshi")))
    }

    /// The files in `dir`.
    pub fn in_dir(dir: &Path) -> Self {
        Self {
            config: dir.join("config"),
            ours: dir.join("sway-things.conf"),
        }
    }

    /// The line the user's kanshi config needs: `include` of ours, with `~` for the home
    /// directory where it is in there.
    pub fn include_line(&self) -> String {
        let home = std::env::var_os("HOME").map(PathBuf::from);
        let shown = home
            .as_deref()
            .and_then(|home| self.ours.strip_prefix(home).ok())
            .map_or_else(
                || self.ours.display().to_string(),
                |relative| format!("~/{}", relative.display()),
            );
        format!("include {shown}")
    }

    /// Whether the file of ours is someone else's: there, with something in it, and without our
    /// header. Nothing is written to it then, so nothing set here reaches kanshi.
    pub fn ours_is_foreign(&self) -> bool {
        std::fs::read_to_string(&self.ours)
            .is_ok_and(|text| !text.trim().is_empty() && !text.starts_with(HEADER))
    }

    /// Whether kanshi has a file of ours to read: there, and not empty. Without, kanshi rejects
    /// the whole config that includes it (or reads nothing of ours).
    pub fn ours_is_written(&self) -> bool {
        std::fs::read_to_string(&self.ours).is_ok_and(|text| text.starts_with(HEADER))
    }

    /// How the user puts the include of ours at the top of their kanshi config, in words: kanshi
    /// applies the first profile that matches, so ours come first. Sway Things never edits the
    /// user's config, and gives no command to paste either: the user changes their own file.
    pub fn how_to_include(&self) -> Text {
        let text = std::fs::read_to_string(&self.config).unwrap_or_default();
        let message = if self.includes_ours(&text) {
            msg!(
                "Put the line {line} at the top of {file}, above your profiles, and take the \
                 line that includes it further down away."
            )
        } else {
            msg!("Put the line {line} at the top of {file}, above your profiles.")
        };
        Text::new(message)
            .arg("line", self.include_line())
            .arg("file", self.config.display())
    }

    /// The user's profiles in their kanshi config that come before the include of ours, which
    /// kanshi tries first ([`overriding`] says which of them win for some displays). Empty
    /// without a config, or without the include.
    pub fn before_ours(&self) -> Vec<(String, Vec<String>)> {
        match std::fs::read_to_string(&self.config) {
            Ok(text) if self.includes_ours(&text) => self.profiles_before_ours(&text),
            _ => Vec::new(),
        }
    }

    /// The profiles of the user's kanshi config `text` that come before the include of ours,
    /// so kanshi tries them first ([`user_profiles`]).
    pub fn profiles_before_ours(&self, text: &str) -> Vec<(String, Vec<String>)> {
        let mut before = String::new();
        // A file included before ours may hold profiles too: named by its line, without displays.
        let mut included = Vec::new();
        for line in text.lines() {
            if self.includes_ours(line) {
                break;
            }
            let written = line.trim();
            if written
                .strip_prefix("include")
                .is_some_and(|rest| rest.starts_with(char::is_whitespace))
            {
                included.push((written.to_owned(), Vec::new()));
            }
            before.push_str(line);
            before.push('\n');
        }
        let mut profiles = user_profiles(&before);
        profiles.extend(included);
        profiles
    }

    /// Whether the user's kanshi config includes ours: [`Inclusion::NoConfig`] if there is
    /// none (it is created then).
    pub fn inclusion(&self) -> Inclusion {
        match std::fs::read_to_string(&self.config) {
            Ok(text) if self.includes_ours(&text) => Inclusion::Included,
            Err(error) if error.kind() == io::ErrorKind::NotFound => Inclusion::NoConfig,
            // Unreadable counts as without the line: nothing is written there.
            Ok(_) | Err(_) => Inclusion::Missing,
        }
    }

    /// Whether `text`, a kanshi config, has an `include` of ours: the path as written, after
    /// `~` and `$HOME`/`$XDG_CONFIG_HOME`, or a pattern with `*` and `?` that matches it.
    fn includes_ours(&self, text: &str) -> bool {
        text.lines().any(|line| {
            let line = line.trim();
            let Some(rest) = line.strip_prefix("include") else {
                return false;
            };
            if !rest.starts_with(char::is_whitespace) {
                return false;
            }
            let path = rest.trim().trim_matches('"');
            let expanded = expand(path);
            expanded == self.ours.to_string_lossy()
                || matches(&expanded, &self.ours.to_string_lossy())
        })
    }

    /// Writes the profiles of `profiles` as our file ([`kanshi_config`], with the placement of the
    /// workspaces) and has kanshi read it again ([`reload`]) if that changed it. Returns whether
    /// it wrote.
    ///
    /// # Errors
    ///
    /// The errors of [`KanshiFiles::write`].
    pub async fn refresh(
        &self,
        profiles: &Profiles,
        places: Option<Placing>,
    ) -> Result<bool, KanshiError> {
        let wrote = self.write(&kanshi_config(profiles, places))?;
        if wrote {
            reload().await;
        }
        Ok(wrote)
    }

    /// Writes `text` (from [`super::profiles::kanshi_config`]) to ours, unless it holds that
    /// already, and creates the user's config with the include line if there is none. A file
    /// of ours that doesn't start with our header is someone else's and left alone. Says whether
    /// anything was written.
    ///
    /// # Errors
    ///
    /// [`KanshiError::Foreign`] if ours is someone else's, else the error of writing.
    pub fn write(&self, text: &str) -> Result<bool, KanshiError> {
        let mut written = false;
        match std::fs::read_to_string(&self.ours) {
            Ok(old) if old == text => {}
            // An empty file is ours to fill: people make one so that kanshi, which rejects its
            // whole config over an include it can't find, starts at all.
            Ok(old) if !old.trim().is_empty() && !old.starts_with(HEADER) => {
                return Err(KanshiError::Foreign(self.ours.clone()));
            }
            Ok(_) => {
                atomic::write(&self.ours, text).map_err(KanshiError::Io)?;
                written = true;
            }
            Err(error) if error.kind() == io::ErrorKind::NotFound => {
                atomic::write(&self.ours, text).map_err(KanshiError::Io)?;
                written = true;
            }
            Err(error) => return Err(KanshiError::Io(error)),
        }
        if self.inclusion() == Inclusion::NoConfig {
            let config = format!(
                "{HEADER}, as there was no kanshi config. Add your own profiles below.\n{}\n",
                self.include_line()
            );
            // Created only if it still isn't there: a file the user made meanwhile stays.
            if let Some(dir) = self.config.parent() {
                std::fs::create_dir_all(dir).map_err(KanshiError::Io)?;
            }
            match std::fs::OpenOptions::new()
                .write(true)
                .create_new(true)
                .open(&self.config)
            {
                Ok(mut file) => {
                    use std::io::Write as _;
                    file.write_all(config.as_bytes()).map_err(KanshiError::Io)?;
                    written = true;
                }
                Err(error) if error.kind() == io::ErrorKind::AlreadyExists => {}
                Err(error) => return Err(KanshiError::Io(error)),
            }
        }
        Ok(written)
    }
}

/// The names of those of `profiles` ([`KanshiFiles::before_ours`]) that kanshi applies instead
/// of ours while the displays `connected` (by their identifiers) are: those whose displays are
/// these, or some of these along with a wildcard. `identifier` gives the identifier of a display
/// as a profile names it (its connector, say).
pub fn overriding(
    profiles: &[(String, Vec<String>)],
    connected: &[&str],
    identifier: impl Fn(&str) -> String,
) -> Vec<String> {
    profiles
        .iter()
        .filter(|(_, outputs)| {
            let any = outputs.iter().any(|criteria| criteria == ANY);
            let ones = outputs.iter().filter(|criteria| *criteria == ONE).count();
            let named: Vec<String> = outputs
                .iter()
                .filter(|criteria| *criteria != ONE && *criteria != ANY)
                .map(|criteria| identifier(criteria))
                .collect();
            // Nothing but the include of another file: what it holds isn't read.
            if named.is_empty() && ones == 0 && !any {
                return false;
            }
            let all_connected = named.iter().all(|name| connected.contains(&name.as_str()));
            let taken = named.len() + ones;
            all_connected && (taken == connected.len() || (any && taken < connected.len()))
        })
        .map(|(name, _)| name.clone())
        .collect()
}

/// Whether the user's kanshi config includes ours.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Inclusion {
    /// It does.
    Included,
    /// There is a config without the line.
    Missing,
    /// There is no config: it is created with the line.
    NoConfig,
}

/// Why the files for kanshi weren't written.
#[derive(Debug)]
pub enum KanshiError {
    /// Our file is there, but Sway Things didn't write it.
    Foreign(PathBuf),
    /// It couldn't be written.
    Io(io::Error),
}

impl KanshiError {
    /// What went wrong, to show.
    pub fn text(&self) -> Text {
        match self {
            Self::Foreign(path) => Text::new(msg!(
                "{file} wasn't written by Sway Things, so it is left alone"
            ))
            .arg("file", path.display()),
            Self::Io(error) => Text::new(msg!("the profiles for kanshi can't be written: {error}"))
                .arg("error", error),
        }
    }
}

impl std::fmt::Display for KanshiError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.text().english())
    }
}

impl std::error::Error for KanshiError {}

/// The profiles of a kanshi config of the user's (`text`): each one's name (or its position,
/// `#1`, for one without) and the displays it names, as written, with `*` for a wildcard.
/// Profiles in included files aren't followed.
pub fn user_profiles(text: &str) -> Vec<(String, Vec<String>)> {
    let mut profiles = Vec::new();
    let mut current: Option<(String, Vec<String>, bool)> = None;
    for line in text.lines().map(str::trim) {
        if let Some(rest) = line.strip_prefix("profile") {
            if rest.is_empty() || rest.starts_with(char::is_whitespace) || rest.starts_with('{') {
                let name = rest
                    .trim()
                    .trim_end_matches('{')
                    .trim()
                    .trim_matches(['"', '\'']);
                let name = if name.is_empty() {
                    format!("#{}", profiles.len() + 1)
                } else {
                    name.to_owned()
                };
                current = Some((name, Vec::new(), false));
                continue;
            }
        }
        if line.starts_with('}') {
            if let Some((name, mut outputs, wildcard)) = current.take() {
                if wildcard {
                    outputs.push(ANY.to_owned());
                }
                if !outputs.is_empty() {
                    profiles.push((name, outputs));
                }
            }
            continue;
        }
        let output = line
            .strip_prefix("...output")
            .or_else(|| line.strip_prefix("output"));
        if let (Some((_, outputs, wildcard)), Some(rest)) = (&mut current, output) {
            let rest = rest.trim();
            let criteria = if let Some(quoted) = rest.strip_prefix('"') {
                quoted.split('"').next().unwrap_or_default().to_owned()
            } else {
                rest.split_whitespace()
                    .next()
                    .unwrap_or_default()
                    .to_owned()
            };
            // `output *` is one more display, `...output *` any number of them.
            if criteria == "*" {
                if line.starts_with("...") {
                    *wildcard = true;
                } else {
                    outputs.push(ONE.to_owned());
                }
            } else if !criteria.is_empty() {
                outputs.push(criteria);
            }
        }
    }
    profiles
}

/// Whether `kanshi` is installed: an executable of that name in a directory of `$PATH`.
pub fn installed() -> bool {
    crate::delegate::find_program("kanshi", std::env::var_os("PATH").as_deref()).is_some()
}

/// Whether the user's sway config starts kanshi itself: an `exec` or `exec_always` with
/// `kanshi` in it, outside the files Sway Things generates in `ours`.
pub fn started_by(config: &SwayConfig, ours: &Path) -> bool {
    config.directives.iter().any(|directive| {
        (directive.is(&[], "exec") || directive.is(&[], "exec_always"))
            && directive.text.contains("kanshi")
            && !directive.file.starts_with(ours)
    })
}

/// Has kanshi read its config again and apply the matching profile: `kanshictl reload`, given
/// five seconds. Best effort: without kanshictl, or without kanshi running, nothing happens.
pub async fn reload() {
    let child = std::process::Command::new("kanshictl")
        .arg("reload")
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .spawn();
    let Ok(mut child) = child else {
        return;
    };
    let until = std::time::Instant::now() + Duration::from_secs(5);
    while matches!(child.try_wait(), Ok(None)) && std::time::Instant::now() < until {
        async_io::Timer::after(Duration::from_millis(50)).await;
    }
    if matches!(child.try_wait(), Ok(None)) {
        let _ = child.kill();
        let _ = child.wait();
    }
}

/// `path` with a leading `~` and `$HOME`, `$XDG_CONFIG_HOME` replaced.
fn expand(path: &str) -> String {
    let home = std::env::var("HOME").unwrap_or_default();
    let config_home = std::env::var("XDG_CONFIG_HOME")
        .ok()
        .filter(|dir| dir.starts_with('/'))
        .unwrap_or_else(|| format!("{home}/.config"));
    let path = match path.strip_prefix('~') {
        Some(rest) if rest.is_empty() || rest.starts_with('/') => format!("{home}{rest}"),
        _ => path.to_owned(),
    };
    path.replace("${XDG_CONFIG_HOME}", &config_home)
        .replace("$XDG_CONFIG_HOME", &config_home)
        .replace("${HOME}", &home)
        .replace("$HOME", &home)
}

/// Whether `text` matches the shell pattern `pattern`, with `*` (any run within a path
/// component) and `?` (one character).
fn matches(pattern: &str, text: &str) -> bool {
    fn go(pattern: &[char], text: &[char]) -> bool {
        match (pattern.split_first(), text.split_first()) {
            (None, None) => true,
            (Some(('*', rest)), _) => {
                go(rest, text)
                    || text
                        .split_first()
                        .is_some_and(|(first, tail)| *first != '/' && go(pattern, tail))
            }
            (Some(('?', rest)), Some((first, tail))) => *first != '/' && go(rest, tail),
            (Some((want, rest)), Some((have, tail))) => want == have && go(rest, tail),
            _ => false,
        }
    }
    let pattern: Vec<char> = pattern.chars().collect();
    let text: Vec<char> = text.chars().collect();
    go(&pattern, &text)
}

#[cfg(test)]
mod tests {
    use super::{Inclusion, KanshiFiles, matches};

    #[test]
    fn the_include_of_ours_is_found_however_it_is_written() {
        let dir = tempfile::tempdir().unwrap();
        let files = KanshiFiles::in_dir(dir.path());
        assert_eq!(files.inclusion(), Inclusion::NoConfig);
        std::fs::write(&files.config, "profile { output * enable }\n").unwrap();
        assert_eq!(files.inclusion(), Inclusion::Missing);
        let ours = files.ours.display().to_string();
        std::fs::write(&files.config, format!("include \"{ours}\"\n")).unwrap();
        assert_eq!(files.inclusion(), Inclusion::Included);
        let pattern = format!("include {}/*.conf\n", dir.path().display());
        std::fs::write(&files.config, pattern).unwrap();
        assert_eq!(files.inclusion(), Inclusion::Included);
        assert!(matches("/a/*.conf", "/a/sway-things.conf"));
        // The way to put it first is said in words: no command to paste.
        let how = files.how_to_include().english();
        assert!(how.starts_with("Put the line include "), "{how}");
        assert!(
            how.ends_with("and take the line that includes it further down away."),
            "{how}"
        );
        std::fs::write(&files.config, "profile {}\n").unwrap();
        let how = files.how_to_include().english();
        assert!(
            how.ends_with(&format!(
                "at the top of {}, above your profiles.",
                files.config.display()
            )),
            "{how}"
        );
        assert!(!matches("/a/*.conf", "/a/b/c.conf"));
    }

    #[test]
    fn the_user_s_profiles_are_read_with_their_displays() {
        let text = "profile 'Home Office' {\n    output \"Dell U27 ABC\" enable\n    \
                    output eDP-1 disable\n}\nprofile {\n    output * enable\n}\n";
        assert_eq!(
            super::user_profiles(text),
            [
                (
                    "Home Office".to_owned(),
                    vec!["Dell U27 ABC".to_owned(), "eDP-1".to_owned()]
                ),
                ("#2".to_owned(), vec!["*".to_owned()]),
            ]
        );
    }

    #[test]
    fn a_profile_of_the_user_s_before_the_include_overrides_ours() {
        let dir = tempfile::tempdir().unwrap();
        let files = KanshiFiles::in_dir(dir.path());
        let include = format!("include {}\n", files.ours.display());
        let desk =
            "profile desk {\n    output eDP-1 disable\n    output \"Dell U27 ABC\" enable\n}\n";
        let any = "profile {\n    output eDP-1 enable\n    ...output * enable\n}\n";
        let named = |criteria: &str| match criteria {
            "eDP-1" => "Laptop Panel 1".to_owned(),
            other => other.to_owned(),
        };
        let none: Vec<String> = Vec::new();
        let connected = ["Laptop Panel 1", "Dell U27 ABC"];
        // Before the include: kanshi tries it first.
        std::fs::write(&files.config, format!("{desk}{include}")).unwrap();
        assert_eq!(
            super::overriding(&files.before_ours(), &connected, named),
            ["desk"]
        );
        // Other displays connected: it doesn't match.
        assert_eq!(
            super::overriding(&files.before_ours(), &["Laptop Panel 1"], named),
            none
        );
        assert_eq!(
            super::overriding(
                &files.before_ours(),
                &["Laptop Panel 1", "Dell U27 ABC", "Beamer"],
                named
            ),
            none
        );
        // With a wildcard, the displays it names only have to be among them.
        std::fs::write(&files.config, format!("{any}{include}")).unwrap();
        assert_eq!(
            super::overriding(&files.before_ours(), &connected, named),
            ["#1"]
        );
        assert_eq!(
            super::overriding(&files.before_ours(), &["Dell U27 ABC"], named),
            none
        );
        // `output *` is exactly one more display; `...output *` any number.
        let one = "profile one {\n    output eDP-1 enable\n    output * enable\n}\n";
        std::fs::write(&files.config, format!("{one}{include}")).unwrap();
        assert_eq!(
            super::overriding(&files.before_ours(), &connected, named),
            ["one"]
        );
        assert_eq!(
            super::overriding(&files.before_ours(), &["Laptop Panel 1", "A", "B"], named),
            none
        );
        assert_eq!(
            super::overriding(&files.before_ours(), &["Laptop Panel 1"], named),
            none
        );
        // A file included before ours isn't read: it never counts as winning now, but it
        // stands above the line.
        std::fs::write(&files.config, format!("include ~/desk.conf\n{include}")).unwrap();
        assert_eq!(
            files.before_ours(),
            [("include ~/desk.conf".to_owned(), vec![])]
        );
        assert_eq!(
            super::overriding(&files.before_ours(), &connected, named),
            none
        );
        // After the include, ours come first; without the include, kanshi isn't ours to follow.
        std::fs::write(&files.config, format!("{include}{desk}")).unwrap();
        assert_eq!(
            super::overriding(&files.before_ours(), &connected, named),
            none
        );
        std::fs::write(&files.config, desk).unwrap();
        assert_eq!(
            super::overriding(&files.before_ours(), &connected, named),
            none
        );
    }

    #[test]
    fn ours_is_written_and_a_missing_config_created() {
        let dir = tempfile::tempdir().unwrap();
        let files = KanshiFiles::in_dir(dir.path());
        let text = "# Generated by Sway Things from x. DO NOT EDIT.\nprofile {}\n";
        assert!(files.write(text).unwrap());
        assert_eq!(std::fs::read_to_string(&files.ours).unwrap(), text);
        assert_eq!(files.inclusion(), Inclusion::Included);
        // Nothing new: nothing written.
        assert!(!files.write(text).unwrap());
        // An empty file of that name (made so kanshi finds its include) is filled.
        std::fs::write(&files.ours, "\n").unwrap();
        assert!(!files.ours_is_written());
        assert!(files.write(text).unwrap());
        assert!(files.ours_is_written());
        assert!(!files.ours_is_foreign());
        // Someone else's file of that name is left alone.
        std::fs::write(&files.ours, "profile mine {}\n").unwrap();
        assert!(files.write(text).is_err());
        assert_eq!(
            std::fs::read_to_string(&files.ours).unwrap(),
            "profile mine {}\n"
        );
    }
}
