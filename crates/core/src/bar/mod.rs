/// The first line of every file Sway Things writes for waybar (as a comment of its syntax); a
/// file that doesn't start with it isn't ours and is never written.
pub const HEADER: &str =
    "Generated by Sway Things from ~/.config/sway-things/settings.toml. DO NOT EDIT.";

/// The second line: where to change it.
pub const HEADER_HINT: &str =
    "Change the bar on the Bar page of Sway Things. Hand edits are overwritten.";

/// The kind of a module: the part of its name before a `#` (`battery` for `battery#bat2`), which
/// is what waybar makes it from. `custom/<name>` and `group/<name>` keep their names, and so on.
pub fn kind_of(name: &str) -> &str {
    name.split('#').next().unwrap_or(name)
}

/// Which bar Sway Things sets up (`bar.backend`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Backend {
    /// None: the user's own bar, whatever it is, stays as it is.
    None,
    /// waybar, with our config and stylesheet.
    Waybar,
    /// swaybar, from `bar` lines in `75-bar.conf`.
    Swaybar,
}

impl Backend {
    /// The backend stored in `state`, or the default (none).
    pub fn of(state: &State) -> Self {
        match value(state, keys::BACKEND) {
            Value::Choice(id) if id == "waybar" => Self::Waybar,
            Value::Choice(id) if id == "swaybar" => Self::Swaybar,
            _ => Self::None,
        }
    }
}

/// The key that shows the bar while held, if `state` shows the bar only then.
pub fn hold_key(state: &State) -> Option<crate::command::bar::Modifier> {
    match value(state, keys::VISIBILITY) {
        Value::Choice(id) if id == "hold" => match value(state, keys::MODIFIER) {
            Value::Choice(name) => crate::command::bar::Modifier::from_name(&name),
            _ => None,
        }
        .or(Some(crate::command::bar::Modifier::Super)),
        _ => None,
    }
}

/// The value of the bar setting `key` in `state`: stored, else its default.
pub(crate) fn value(state: &State, key: &str) -> Value {
    state.get(key, None).cloned().unwrap_or_else(|| {
        Registry::builtin()
            .get(key)
            .map_or(Value::Bool(false), crate::registry::Setting::default_value)
    })
}

/// The files Sway Things writes for waybar.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WaybarFiles {
    /// The directory, normally `$XDG_CONFIG_HOME/sway-things/waybar`.
    pub dir: PathBuf,
}

impl WaybarFiles {
    /// The files in `config_dir/waybar`, where `config_dir` is that of the settings files
    /// (normally `$XDG_CONFIG_HOME/sway-things`).
    pub fn in_config_dir(config_dir: &Path) -> Self {
        Self {
            dir: config_dir.join("waybar"),
        }
    }

    /// The files next to the settings files of `state`.
    pub fn of(state: &State) -> Option<Self> {
        let shared = state.paths().path(crate::state::Layer::Shared);
        shared.parent().map(Self::in_config_dir)
    }

    /// The config, `config.jsonc`.
    pub fn config(&self) -> PathBuf {
        self.dir.join("config.jsonc")
    }

    /// The stylesheet waybar is started with, `style.css`.
    pub fn style(&self) -> PathBuf {
        self.dir.join("style.css")
    }

    /// The directory the templates of custom modules are copied to on request.
    pub fn scripts(&self) -> PathBuf {
        self.dir.join("scripts")
    }

    /// Writes `text` to `path` if it isn't there already, unless the file there isn't ours (it
    /// doesn't start with `comment` followed by our [`HEADER`]). Says whether it wrote.
    ///
    /// # Errors
    ///
    /// [`BarError::Foreign`] for a file that isn't ours, [`BarError::Io`] if it can't be read or
    /// written.
    pub fn write(path: &Path, comment: &str, text: &str) -> Result<bool, BarError> {
        match std::fs::read_to_string(path) {
            Ok(old) if old == text => return Ok(false),
            Ok(old) if !is_ours(&old, comment) => return Err(BarError::Foreign(path.to_owned())),
            Ok(_) => {}
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
            Err(error) => return Err(BarError::Io(path.to_owned(), error.to_string())),
        }
        atomic::write(path, text)
            .map_err(|error| BarError::Io(path.to_owned(), error.to_string()))?;
        Ok(true)
    }

    /// Whether the file at `path` is missing or ours.
    pub fn is_ours_or_missing(path: &Path, comment: &str) -> bool {
        match std::fs::read_to_string(path) {
            Ok(text) => is_ours(&text, comment),
            Err(error) => error.kind() == std::io::ErrorKind::NotFound,
        }
    }
}

/// Whether `text` starts with our header after the comment marker `comment` (`//`, `/*`).
fn is_ours(text: &str, comment: &str) -> bool {
    text.strip_prefix(comment)
        .is_some_and(|rest| rest.trim_start().starts_with(HEADER))
}

/// What went wrong with the files of the bar.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum BarError {
    /// A file in the place of ours that Sway Things didn't write; it is left alone.
    Foreign(PathBuf),
    /// A file couldn't be read or written, with the system's error.
    Io(PathBuf, String),
}

impl BarError {
    /// What went wrong, to show.
    pub fn text(&self) -> Text {
        match self {
            Self::Foreign(path) => Text::new(msg!(
                "{path} wasn't written by Sway Things, so it stays as it is. Move it away to let \
                 Sway Things write the bar's file there"
            ))
            .text("path", Text::data(path.display().to_string())),
            Self::Io(path, error) => Text::new(msg!("Can't write {path}: {error}"))
                .text("path", Text::data(path.display().to_string()))
                .text("error", Text::data(error.clone())),
        }
    }
}

impl std::fmt::Display for BarError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.text().english())
    }
}

impl std::error::Error for BarError {}

/// `path` with `~` for the home directory, as people write it.
pub fn tilde(path: &Path) -> String {
    let home = std::env::var_os("HOME").map(PathBuf::from);
    match home
        .as_deref()
        .and_then(|home| path.strip_prefix(home).ok())
    {
        Some(relative) => format!("~/{}", relative.display()),
        None => path.display().to_string(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn module_names_and_kinds() {
        assert!(is_module_name("clock"));
        assert!(is_module_name("custom/claude#detail"));
        assert!(!is_module_name(""));
        assert!(!is_module_name("two words"));
        assert!(!is_module_name("line\nbreak"));
        assert!(!is_module_name(&"x".repeat(129)));
        assert_eq!(kind_of("battery#bat2"), "battery");
        assert_eq!(kind_of("custom/vpn#1"), "custom/vpn");
        assert_eq!(kind_of("clock"), "clock");
    }

    #[test]
    fn only_files_of_ours_are_written() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("waybar/config.jsonc");
        let ours = format!("// {HEADER}\n{{}}\n");
        assert_eq!(WaybarFiles::write(&path, "//", &ours), Ok(true));
        assert_eq!(WaybarFiles::write(&path, "//", &ours), Ok(false));
        let newer = format!("// {HEADER}\n{{\"height\": 30}}\n");
        assert_eq!(WaybarFiles::write(&path, "//", &newer), Ok(true));
        std::fs::write(&path, "{\"mine\": true}").unwrap();
        assert_eq!(
            WaybarFiles::write(&path, "//", &ours),
            Err(BarError::Foreign(path.clone()))
        );
        assert_eq!(std::fs::read_to_string(&path).unwrap(), "{\"mine\": true}");
        assert!(!WaybarFiles::is_ours_or_missing(&path, "//"));
        assert!(WaybarFiles::is_ours_or_missing(
            &dir.path().join("none"),
            "//"
        ));
    }
}
