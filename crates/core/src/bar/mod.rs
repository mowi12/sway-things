//! The bar: waybar through a handover, or swaybar through our sway include.
//!
//! waybar's own `include` lets the first definition of a key win, so an included file could only
//! add modules, never change what the user's config sets. So Sway Things writes a complete config
//! and stylesheet of its own to `$XDG_CONFIG_HOME/sway-things/waybar/` ([`WaybarFiles`]), each
//! starting with our header, and the user's waybar config is never written. waybar is pointed at
//! them with `-c` and `-s`: by the user's own `exec waybar` line, which the page shows the change
//! for ([`process::Starter`]; a `bar` block with `swaybar_command waybar` goes instead, since sway
//! runs that command without options), or by `75-bar.conf`, which runs
//! `sway-things hook waybar` ([`process::ensure`]). A change reaches waybar with `SIGUSR2`, sent
//! only to the waybar processes of this session that run our config ([`process::reload`]).
//!
//! What the config holds comes from the registry's `bar.*` settings (where the bar stands, the
//! module lists, the style) and from the module definitions in `bar.jsonc` next to the settings
//! files ([`Modules`]): each module's options as waybar takes them, kept as JSON, so options the
//! page doesn't know pass through unchanged. The [`catalog`] describes the common modules and the
//! options its forms offer. [`import`] reads the user's waybar config (comments, `include`s) as a
//! starting point, and only reads it.
//!
//! swaybar needs no files of its own: [`swaybar::lines`] are `bar sway-things …` commands for
//! `75-bar.conf`, built by the typed command builders.

