use std::collections::BTreeSet;

use crate::command::Target;
use crate::command::input::InputSelector;
use crate::ipc::Compositor;
use crate::registry::{ConfigFile, Registry, Setting};
use crate::state::State;

pub use manifest::{Manifest, Ownership};

/// The first lines of every generated file. A file that starts with them was generated by Sway
/// Things.
pub const HEADER: &str = "\
# Generated by Sway Things from ~/.config/sway-things/settings.toml. DO NOT EDIT.
# Change settings in the app or with `sway-things set`. Hand edits are overwritten.
";

/// The files in the order of their names.
const FILES: [ConfigFile; 4] = [
    ConfigFile::Input,
    ConfigFile::Appearance,
    ConfigFile::Behavior,
    ConfigFile::Effects,
];

/// The stored settings a line of a generated file comes from.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Source {
    /// The keys of the stored settings. Several, if they are values of one directive.
    pub keys: Vec<&'static str>,
    /// The input device the line is for, or `None` for the whole session or input type.
    pub device: Option<String>,
}

/// A line of a generated file below the header.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Line {
    /// The text, without the line break.
    pub text: String,
    /// The settings the line comes from.
    pub source: Source,
    /// `None` for a command. Otherwise the line is a comment that names the settings and says why
    /// their command is left out: the compositor doesn't support it, or a stored value can't be
    /// turned into a command.
    pub skipped: Option<String>,
}

/// The contents of one generated file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedFile {
    file: ConfigFile,
    lines: Vec<Line>,
}

impl GeneratedFile {
    /// Which file this is.
    pub fn file(&self) -> ConfigFile {
        self.file
    }

    /// The lines below the header.
    pub fn lines(&self) -> &[Line] {
        &self.lines
    }

    /// Whether the file holds nothing but the header.
    pub fn is_empty(&self) -> bool {
        self.lines.is_empty()
    }

    /// The text of the file.
    pub fn text(&self) -> String {
        let mut text = HEADER.to_owned();
        for line in &self.lines {
            text.push_str(&line.text);
            text.push('\n');
        }
        text
    }

    /// The settings behind the line with the number `line` (counted from 1, as sway reports
    /// errors), or `None` for a line of the header or beyond the end.
    pub fn source_of_line(&self, line: usize) -> Option<&Source> {
        let below_header = line.checked_sub(HEADER.lines().count() + 1)?;
        self.lines.get(below_header).map(|line| &line.source)
    }
}

/// Generates the contents of every sway config file from the stored settings in `state`, for
/// `compositor`.
///
/// A stored setting that `compositor` doesn't support becomes a comment instead of a command, so
/// the file stays valid: a SwayFX effect on sway, or a value that needs a newer sway. The value
/// stays stored and comes back when the compositor supports it. The same happens to a value the
/// command builders reject, such as a font description with a backslash.
pub fn generate(registry: &Registry, state: &State, compositor: Compositor) -> Vec<GeneratedFile> {
    let mut files = FILES.map(|file| GeneratedFile {
        file,
        lines: Vec::new(),
    });
    let entries = state.entries();
    let devices: BTreeSet<Option<&str>> = entries.iter().map(|entry| entry.device).collect();
    // `None` sorts first: the lines for input types come before those for single devices.
    for device in devices {
        for setting in registry.iter() {
            let Some(mapping) = setting.sway() else {
                continue;
            };
            // The settings of one directive make one command, at the place of the first one.
            let group: Vec<&Setting> = registry.group(setting).collect();
            if group.first().map(|first| first.key()) != Some(setting.key()) {
                continue;
            }
            let keys: Vec<&'static str> = group
                .iter()
                .map(|member| member.key())
                .filter(|key| state.get(key, device).is_some())
                .collect();
            if keys.is_empty() {
                continue;
            }
            let source = Source {
                keys,
                device: device.map(ToOwned::to_owned),
            };
            if let Some(file) = files.iter_mut().find(|file| file.file == mapping.file()) {
                file.lines
                    .extend(lines(registry, state, compositor, setting, &source));
            }
        }
    }
    files.into()
}

/// The lines for the directive of `setting`: its commands, or one comment if they are left out.
fn lines(
    registry: &Registry,
    state: &State,
    compositor: Compositor,
    setting: &Setting,
    source: &Source,
) -> Vec<Line> {
    let skipped = |reason: String| {
        let device = match &source.device {
            Some(device) => format!(" (device {device})"),
            None => String::new(),
        };
        vec![Line {
            text: format!("# {}{device}: {reason}", source.keys.join(", ")),
            source: source.clone(),
            skipped: Some(reason),
        }]
    };
    let requirements = setting.requirements();
    if let Err(unmet) = compositor.check(requirements.min_sway, requirements.min_swayfx) {
        return skipped(unmet.to_string());
    }
    let device = source.device.as_deref();
    let selector = match device.map(InputSelector::device) {
        Some(Ok(selector)) => Some(selector),
        Some(Err(error)) => return skipped(error.to_string()),
        None => None,
    };
    let commands = match registry.render(
        setting,
        &state.values(device),
        selector.as_ref(),
        Target::Config,
    ) {
        Ok(commands) => commands,
        Err(error) => return skipped(error.to_string()),
    };
    let mut lines = Vec::with_capacity(commands.len());
    for command in commands {
        // A value can need a newer compositor than its setting.
        if let Err(unmet) = compositor.supports(&command) {
            return skipped(unmet.to_string());
        }
        match command.render(Target::Config) {
            Ok(text) => lines.push(Line {
                text,
                source: source.clone(),
                skipped: None,
            }),
            Err(error) => return skipped(error.to_string()),
        }
    }
    lines
}
