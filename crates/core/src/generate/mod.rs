//! The sway config files Sway Things generates from the settings state.
//!
//! [`generate`] turns the stored settings into the contents of the files in
//! `$XDG_CONFIG_HOME/sway/sway-things/`, which the user's config includes. It writes nothing, so
//! it also serves "Show generated config".
//!
//! Every file starts with the [`HEADER`]. Below it, each line is one command as the
//! [command builders](crate::command) render it for a config file, in the order of the registry,
//! first for the whole session and the input types, then per input device. The same state gives
//! the same bytes.
//!
//! ```
//! use sway_things_core::generate::generate;
//! use sway_things_core::ipc::Compositor;
//! use sway_things_core::registry::{ConfigFile, Registry, Value};
//! use sway_things_core::state::{Paths, State};
//! use sway_things_core::version::SwayVersion;
//!
//! # let dir = tempfile::tempdir()?;
//! # let (config_dir, state_dir) = (&dir.path().join("config"), &dir.path().join("state"));
//! let registry = Registry::builtin();
//! let mut state = State::load(registry, Paths::new(config_dir, state_dir, "laptop")?);
//! state.set("input.touchpad.tap", None, Value::Bool(true), None)?;
//!
//! let sway = Compositor::Sway { version: SwayVersion::new(1, 11, 0) };
//! let files = generate(registry, &state, sway);
//! let input = files.iter().find(|file| file.file() == ConfigFile::Input).ok_or("no file")?;
//! assert!(input.text().ends_with("\ninput type:touchpad tap enabled\n"));
//! # Ok::<(), Box<dyn std::error::Error>>(())
//! ```

