/// The first lines of every generated file. A file that starts with them was generated by Sway
/// Things.
pub const HEADER: &str = "\
# Generated by Sway Things from ~/.config/sway-things/settings.toml. DO NOT EDIT.
# Change settings in the app or with `sway-things set`. Hand edits are overwritten.
";

/// The stored settings a line of a generated file comes from.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Source {
    /// The keys of the stored settings. Several, if they are values of one directive.
    pub keys: Vec<&'static str>,
    /// The input device the line is for, or `None` for the whole session or input type.
    pub device: Option<String>,
}

/// A line of a generated file below the header.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Line {
    /// The text, without the line break.
    pub text: String,
    /// The settings the line comes from.
    pub source: Source,
    /// `None` for a command. Otherwise the line is a comment that names the settings and says why
    /// their command is left out: the compositor doesn't support it, or a stored value can't be
    /// turned into a command.
    pub skipped: Option<String>,
}

/// The contents of one generated file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedFile {
    file: ConfigFile,
    lines: Vec<Line>,
}

impl GeneratedFile {
    /// Which file this is.
    pub fn file(&self) -> ConfigFile {
        self.file
    }

    /// The lines below the header.
    pub fn lines(&self) -> &[Line] {
        &self.lines
    }

    /// Whether the file holds nothing but the header.
    pub fn is_empty(&self) -> bool {
        self.lines.is_empty()
    }

    /// The text of the file.
    pub fn text(&self) -> String {
        let mut text = HEADER.to_owned();
        for line in &self.lines {
            text.push_str(&line.text);
            text.push('\n');
        }
        text
    }

    /// The settings behind the line with the number `line` (counted from 1, as sway reports
    /// errors), or `None` for a line of the header or beyond the end.
    pub fn source_of_line(&self, line: usize) -> Option<&Source> {
        let below_header = line.checked_sub(HEADER.lines().count() + 1)?;
        self.lines.get(below_header).map(|line| &line.source)
    }
}

/// Generates the contents of every sway config file from the stored settings in `state`, for
/// `compositor`.
///
/// A stored setting that `compositor` doesn't support becomes a comment instead of a command, so
/// the file stays valid: a SwayFX effect on sway, or a value that needs a newer sway. The value
/// stays stored and comes back when the compositor supports it. The same happens to a value the
/// command builders reject, such as a font description with a backslash.
pub fn generate(registry: &Registry, state: &State, compositor: Compositor) -> Vec<GeneratedFile> {
    generate_for(registry, state, compositor, Displays::Sway)
}

/// Who sets up the displays: what decides whether the generated sway config has `output` lines.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Displays {
    /// sway, from the `output` lines Sway Things generates.
    #[default]
    Sway,
    /// kanshi, from the profiles Sway Things remembers per combination of displays
    /// ([`crate::outputs::profiles`]): kanshi applies them whenever displays come and go, so
    /// the sway config has no `output` lines that would contradict them at a reload. With
    /// `start`, the user's config doesn't start kanshi, so ours does.
    Kanshi {
        /// Whether the generated config starts kanshi.
        start: bool,
    },
}

impl Displays {
    /// kanshi if it is installed and its config includes ours (or there is none, so it is
    /// created with the include), else sway. `status` is the user's sway config, which may start
    /// kanshi itself; `locations` are our files in it. Reads files; nothing is run.
    pub fn detect(status: &crate::include::IncludeStatus, locations: &Locations) -> Self {
        use crate::outputs::kanshi;
        let Some(files) = kanshi::KanshiFiles::from_env() else {
            return Self::Sway;
        };
        if !kanshi::installed() || files.inclusion() == kanshi::Inclusion::Missing {
            return Self::Sway;
        }
        // Started by the user's sway config, or running from elsewhere (a systemd unit, say):
        // one kanshi is enough. A kanshi our own `exec kanshi` started keeps being started,
        // until one runs as a unit of its own: that one was set up since, and ours would be a
        // second one beside it.
        let ours_starts = std::fs::read_to_string(locations.path(ConfigFile::Output))
            .is_ok_and(|text| text.lines().any(|line| line.trim() == "exec kanshi"));
        Self::Kanshi {
            start: !kanshi::started_by(status.config(), locations.directory())
                && !crate::outputs::kanshi_runs_as_unit()
                && (ours_starts || !crate::outputs::kanshi_runs()),
        }
    }

    /// This, or sway if the remembered displays aren't `readable` (`displays.toml` can't be
    /// read): kanshi would get nothing of what is set, so sway keeps setting the displays up
    /// from our lines. The app, the command line and `doctor` all decide by this.
    #[must_use]
    pub fn with_profiles(self, readable: bool) -> Self {
        if readable { self } else { Self::Sway }
    }

    /// Whether kanshi sets up the displays.
    pub fn is_kanshi(self) -> bool {
        matches!(self, Self::Kanshi { .. })
    }
}

/// [`generate`] with `displays` set up by sway or by kanshi.
pub fn generate_for(
    registry: &Registry,
    state: &State,
    compositor: Compositor,
    displays: Displays,
) -> Vec<GeneratedFile> {
    let mut files = ConfigFile::ALL.map(|file| GeneratedFile {
        file,
        lines: Vec::new(),
    });
    let entries = state.entries();
    let devices: BTreeSet<Option<&str>> = entries.iter().map(|entry| entry.device).collect();
    // `None` sorts first: the lines for input types come before those for single devices.
    for device in devices {
        for setting in registry.iter() {
            let Some(mapping) = setting.sway() else {
                continue;
            };
            if displays.is_kanshi() && setting.sets_up_display() {
                continue;
            }
            // The settings of one directive make one command, at the place of the first one.
            let group: Vec<&Setting> = registry.group(setting).collect();
            if group.first().map(|first| first.key()) != Some(setting.key()) {
                continue;
            }
            let keys: Vec<&'static str> = group
                .iter()
                .map(|member| member.key())
                .filter(|key| state.get(key, device).is_some())
                .collect();
            if keys.is_empty() {
                continue;
            }
            let source = Source {
                keys,
                device: device.map(ToOwned::to_owned),
            };
            if let Some(file) = files.iter_mut().find(|file| file.file == mapping.file()) {
                file.lines
                    .extend(lines(registry, state, compositor, setting, &source));
            }
        }
    }
    if let Some(file) = files
        .iter_mut()
        .find(|file| file.file == ConfigFile::Bindings)
    {
        file.lines.extend(bindings(state));
    }
    if let Some(file) = files
        .iter_mut()
        .find(|file| file.file == ConfigFile::Autostart)
    {
        file.lines.extend(autostart(state));
    }
    if let Some(file) = files.iter_mut().find(|file| file.file == ConfigFile::Hooks) {
        file.lines.extend(hooks(registry, state));
        file.lines.extend(notification_daemon(state));
    }
    if let Some(file) = files
        .iter_mut()
        .find(|file| file.file == ConfigFile::Output)
    {
        file.lines.extend(output_tail(state, displays));
    }
    files.into()
}

/// The lines at the end of `20-output.conf`, after the settings of the outputs: with kanshi, what
/// starts and serves it, and the display guard.
fn output_tail(state: &State, displays: Displays) -> Vec<Line> {
    let mut lines = Vec::new();
    let for_displays = state
        .entries()
        .iter()
        .any(|entry| entry.setting.sets_up_display());
    if displays.is_kanshi() && for_displays {
        lines.push(Line {
            text: "# kanshi sets up the displays from ~/.config/kanshi/sway-things.conf."
                .to_owned(),
            source: Source {
                keys: Vec::new(),
                device: None,
            },
            skipped: None,
        });
    }
    if displays == (Displays::Kanshi { start: true }) {
        if let Ok(text) = crate::command::SwayCmd::new("exec")
            .keyword("kanshi")
            .render(Target::Config)
        {
            lines.push(Line {
                text,
                source: Source {
                    keys: Vec::new(),
                    device: None,
                },
                skipped: None,
            });
        }
    }
    // The picture of another display doesn't take the focus when it starts.
    if displays.is_kanshi() {
        if let Ok(text) = crate::outputs::mirror::no_focus_command().render(Target::Config) {
            lines.push(Line {
                text,
                source: Source {
                    keys: Vec::new(),
                    device: None,
                },
                skipped: None,
            });
        }
    }
    // With kanshi, the hook also has kanshi apply its profile again and places the
    // workspaces after every reload, whatever is stored.
    let guard = display_guard(state).or_else(|| {
        displays.is_kanshi().then(|| {
            outputs::guard_command()
                .render(Target::Config)
                .ok()
                .map(|text| Line {
                    text,
                    source: Source {
                        keys: Vec::new(),
                        device: None,
                    },
                    skipped: None,
                })
        })?
    });
    lines.extend(guard);
    // One line for every output with a collection: it names none, see `wallpaper::start_command`.
    if let Some(first) = crate::wallpaper::shown(state).first() {
        if let Ok(text) = crate::wallpaper::start_command().render(Target::Config) {
            lines.push(Line {
                text,
                source: Source {
                    keys: vec![crate::wallpaper::COLLECTION],
                    device: first.output.clone(),
                },
                skipped: None,
            });
        }
    }
    lines
}

/// The lines of `50-bindings.conf`: the bindings of the Keyboard Shortcuts page
/// ([`crate::bindings::ours::file_lines`]). An item that can't be written becomes a comment.
fn bindings(state: &State) -> Vec<Line> {
    let items = crate::bindings::ours::items(state);
    crate::bindings::ours::file_lines(state)
        .into_iter()
        .map(|file_line| {
            // An item that can't be written is named, so the comment and `doctor` say which.
            let item = match file_line.origin {
                crate::bindings::Origin::Item(index) => items.get(index),
                _ => None,
            };
            let source = Source {
                keys: vec![file_line.key()],
                device: None,
            };
            let text = file_line
                .command()
                .map_err(|error| match item {
                    Some(item) => format!("{item}: {}", error.text().english()),
                    None => error.text().english(),
                })
                .and_then(|command| {
                    command
                        .render(Target::Config)
                        .map_err(|error| error.to_string())
                });
            match text {
                Ok(text) => Line {
                    text,
                    source,
                    skipped: None,
                },
                Err(reason) => Line {
                    text: format!("# {}: {reason}", source.keys.join(", ")),
                    source,
                    skipped: Some(reason),
                },
            }
        })
        .collect()
}

/// The lines of `70-autostart.conf`: the runner of the XDG autostart entries and the entries of
/// the Apps & Autostart page ([`crate::apps::autostart::file_lines`]). An item that can't be
/// written becomes a comment.
fn autostart(state: &State) -> Vec<Line> {
    crate::apps::autostart::file_lines(state)
        .into_iter()
        .map(|file_line| {
            let source = Source {
                keys: vec![file_line.key],
                device: None,
            };
            let text = file_line.command.and_then(|command| {
                command
                    .render(Target::Config)
                    .map_err(|error| error.to_string())
            });
            match text {
                Ok(text) => Line {
                    text,
                    source,
                    skipped: None,
                },
                Err(reason) => Line {
                    text: format!("# {}: {reason}", source.keys.join(", ")),
                    source,
                    skipped: Some(reason),
                },
            }
        })
        .collect()
}

/// The line of `80-hooks.conf` that starts the notification daemon chosen on the
/// Notifications page (`notifications.start`) through `sway-things hook notification-daemon`.
fn notification_daemon(state: &State) -> Option<Line> {
    use crate::notifications::Daemon;
    use crate::registry::notifications::START;
    let Some(crate::registry::Value::Choice(program)) = state.get(START, None) else {
        return None;
    };
    Daemon::from_program(program)?;
    Some(hook_line(command::Hook::NotificationDaemon, vec![START]))
}

/// The lines of `80-hooks.conf`: `sway-things hook gsettings` while a setting with a GSettings key
/// is stored, so its value reaches GSettings at login and after each reload, also when the
/// settings file came from another machine; and `sway-things hook workspaces` while the
/// workspaces are placed, since sway forgets their displays at a reload; `sway-things hook
/// clipboard` while the clipboard history is on, which starts its watcher once per session;
/// `sway-things hook night-light` while the night light is on, which starts its tool; and
/// `sway-things hook timezone` once at login while the automatic time zone is on.
fn hooks(registry: &Registry, state: &State) -> Vec<Line> {
    let mut lines = Vec::new();
    let keys: Vec<&'static str> = registry
        .iter()
        .filter(|setting| setting.gsettings().is_some())
        .map(Setting::key)
        .filter(|key| state.get(key, None).is_some())
        .collect();
    if !keys.is_empty() {
        lines.push(hook_line(command::Hook::Gsettings, keys));
    }
    if crate::capture::is_on(state, crate::capture::HISTORY) {
        lines.push(hook_line(
            command::Hook::Clipboard,
            vec![crate::capture::HISTORY],
        ));
    }
    if crate::night_light::Settings::of(state).on {
        lines.push(hook_line(
            command::Hook::NightLight,
            vec![crate::night_light::ENABLED],
        ));
    }
    if outputs::workspaces::Rule::of(state).places() {
        lines.push(hook_line(
            command::Hook::Workspaces,
            vec![crate::registry::workspaces::PLACEMENT],
        ));
    }
    let automatic_timezone = crate::registry::region::AUTOMATIC_TIMEZONE;
    if state.get(automatic_timezone, None) == Some(&crate::registry::Value::Bool(true)) {
        lines.push(line_of(
            &command::hook_at_start(command::Hook::Timezone),
            vec![automatic_timezone],
        ));
    }
    lines
}

/// The line that runs `sway-things hook <name>`, for the settings `keys`.
fn hook_line(hook: command::Hook, keys: Vec<&'static str>) -> Line {
    line_of(&command::hook(hook), keys)
}

/// The line of `command`, for the settings `keys`; a comment if it can't be rendered.
fn line_of(command: &command::SwayCmd, keys: Vec<&'static str>) -> Line {
    let source = Source { keys, device: None };
    match command.render(Target::Config) {
        Ok(text) => Line {
            text,
            source,
            skipped: None,
        },
        Err(error) => Line {
            text: format!("# {}: {error}", source.keys.join(", ")),
            source,
            skipped: Some(error.to_string()),
        },
    }
}

/// While Sway Things stores anything for an output, the line that runs `sway-things hook
/// displays` whenever sway starts or reloads: it switches an output on if none is on, so an
/// output that stays off never leaves the user without a display (a laptop's panel, switched off
/// at the dock, when sway starts without the dock), even where a line of the user's switches off
/// what is stored as on; and while kanshi runs, it has kanshi apply its profile again over the
/// lines sway just read.
fn display_guard(state: &State) -> Option<Line> {
    let entries = state.entries();
    let first = entries
        .iter()
        .find(|entry| entry.setting.sets_up_display())?;
    let text = outputs::guard_command().render(Target::Config).ok()?;
    Some(Line {
        text,
        source: Source {
            keys: vec![first.setting.key()],
            device: first.device.map(ToOwned::to_owned),
        },
        skipped: None,
    })
}

/// The lines for the directive of `setting`: its commands, or one comment if they are left out.
fn lines(
    registry: &Registry,
    state: &State,
    compositor: Compositor,
    setting: &Setting,
    source: &Source,
) -> Vec<Line> {
    let skipped = |reason: String| {
        let device = match &source.device {
            Some(device) => format!(" (device {device})"),
            None => String::new(),
        };
        vec![Line {
            text: format!("# {}{device}: {reason}", source.keys.join(", ")),
            source: source.clone(),
            skipped: Some(reason),
        }]
    };
    let requirements = setting.requirements();
    if let Err(unmet) = compositor.check(requirements.min_sway, requirements.min_swayfx) {
        return skipped(unmet.to_string());
    }
    let device = source.device.as_deref();
    let commands = match registry.render(setting, &state.values(device), device, Target::Config) {
        Ok(commands) => commands,
        Err(error) => return skipped(error.to_string()),
    };
    let mut lines = Vec::with_capacity(commands.len());
    for command in commands {
        // A value can need a newer compositor than its setting.
        if let Err(unmet) = compositor.supports(&command) {
            return skipped(unmet.to_string());
        }
        match command.render(Target::Config) {
            Ok(text) => lines.push(Line {
                text,
                source: source.clone(),
                skipped: None,
            }),
            Err(error) => return skipped(error.to_string()),
        }
    }
    lines
}
