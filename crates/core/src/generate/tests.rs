pub(super) const TOUCHPAD: &str = "1267:12377:ELAN1300:00_04F3:3059_Touchpad";

pub(super) const SWAY_1_10: Compositor = Compositor::Sway {
    version: SwayVersion::new(1, 10, 1),
};
pub(super) const SWAYFX_0_5: Compositor = Compositor::SwayFx {
    version: SwayFxVersion::new(0, 5, 0),
    base: SwayVersion::new(1, 10, 1),
};

/// A state with the given shared file and host overlay.
pub(super) fn state(shared: &str, host: &str) -> (tempfile::TempDir, State) {
    let dir = tempfile::tempdir().unwrap();
    let config = dir.path().join("config");
    fs::create_dir_all(config.join("settings.d")).unwrap();
    fs::write(config.join("settings.toml"), shared).unwrap();
    fs::write(config.join("settings.d/laptop.toml"), host).unwrap();
    let paths = Paths::new(&config, &dir.path().join("state"), "laptop").unwrap();
    let state = State::load(Registry::builtin(), paths);
    assert_eq!(state.problems(), []);
    (dir, state)
}

/// A setting of every generated file, one directive with several values, and a device.
pub(super) fn sample() -> (tempfile::TempDir, State) {
    state(
        r##"version = 1

[behavior]
workspace_layout = "tabbed"
focus_follows_mouse = "always"

[effects]
corner_radius = 8

[windows]
font = "Inter \"Display\" $11"

[windows.focused]
child_border = "#3b6e4f"
text = "#eeeeee"

[windows.gaps]
inner = 8

[input.keyboard]
xkb_layout = ["us", "de"]
repeat_delay = 300

[input.touchpad]
tap = true
"##,
        &format!(
            r#"version = 1

[input.touchpad]
pointer_accel = 0.3

[device."{TOUCHPAD}".input.touchpad]
tap = false
"#
        ),
    )
}

fn text(files: &[GeneratedFile], file: ConfigFile) -> String {
    let file = files.iter().find(|generated| generated.file() == file);
    file.unwrap().text()
}

#[test]
fn an_empty_state_generates_only_headers() {
    let (_dir, state) = state("", "");
    let files = generate(Registry::builtin(), &state, SWAY_1_10);
    assert_eq!(
        files.iter().map(GeneratedFile::file).collect::<Vec<_>>(),
        [
            ConfigFile::Input,
            ConfigFile::Appearance,
            ConfigFile::Behavior,
            ConfigFile::Effects
        ]
    );
    for file in files {
        assert!(file.is_empty());
        assert_eq!(file.text(), HEADER);
        assert!(file.text().starts_with("# Generated by Sway Things "));
    }
}

#[test]
fn every_file_is_generated_from_the_stored_settings() {
    let (_dir, state) = sample();
    let files = generate(Registry::builtin(), &state, SWAYFX_0_5);
    // In the order of the registry, the input types before the devices; the overlay wins.
    assert_eq!(
        text(&files, ConfigFile::Input),
        format!(
            "{HEADER}\
input type:touchpad tap enabled
input type:touchpad pointer_accel 0.3
input type:keyboard repeat_delay 300
input type:keyboard xkb_layout \"us,de\"
input \"{TOUCHPAD}\" tap disabled
"
        )
    );
    // One line for the two stored colors of `client.focused`, the others at their defaults.
    assert_eq!(
        text(&files, ConfigFile::Appearance),
        format!(
            "{HEADER}\
client.focused #4c7899 #285577 #eeeeee #2e9ef4 #3b6e4f
gaps inner 8
font \"Inter \\\"Display\\\" $$11\"
"
        )
    );
    assert_eq!(
        text(&files, ConfigFile::Behavior),
        format!(
            "{HEADER}\
focus_follows_mouse always
workspace_layout tabbed
"
        )
    );
    assert_eq!(
        text(&files, ConfigFile::Effects),
        format!("{HEADER}corner_radius 8\n")
    );
    assert!(files.iter().all(|file| !file.is_empty()));
    assert!(
        files
            .iter()
            .flat_map(GeneratedFile::lines)
            .all(|line| line.skipped.is_none())
    );
}

