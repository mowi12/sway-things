use std::fs;

use super::{GeneratedFile, HEADER, Source, generate};
use crate::ipc::Compositor;
use crate::registry::{ConfigFile, Registry};
use crate::state::{Paths, State};
use crate::version::{SwayFxVersion, SwayVersion};

pub(super) const TOUCHPAD: &str = "1267:12377:ELAN1300:00_04F3:3059_Touchpad";

pub(super) const SWAY_1_10: Compositor = Compositor::Sway {
    version: SwayVersion::new(1, 10, 1),
};
pub(super) const SWAYFX_0_5: Compositor = Compositor::SwayFx {
    version: SwayFxVersion::new(0, 5, 0),
    base: SwayVersion::new(1, 10, 1),
};

/// A state with the given shared file and host overlay.
pub(super) fn state(shared: &str, host: &str) -> (tempfile::TempDir, State) {
    let dir = tempfile::tempdir().unwrap();
    let config = dir.path().join("config");
    fs::create_dir_all(config.join("settings.d")).unwrap();
    fs::write(config.join("settings.toml"), shared).unwrap();
    fs::write(config.join("settings.d/laptop.toml"), host).unwrap();
    let paths = Paths::new(&config, &dir.path().join("state"), "laptop").unwrap();
    let state = State::load(Registry::builtin(), paths);
    assert_eq!(state.problems(), []);
    (dir, state)
}

/// A setting of every generated file, one directive with several values, and a device.
pub(super) fn sample() -> (tempfile::TempDir, State) {
    state(
        r##"version = 1

[behavior]
workspace_layout = "tabbed"
focus_follows_mouse = "always"

[effects]
corner_radius = 8

[windows]
font = "Inter \"Display\" $11"

[windows.focused]
child_border = "#3b6e4f"
text = "#eeeeee"

[windows.gaps]
inner = 8

[input.keyboard]
xkb_layout = ["us", "de"]
repeat_delay = 300

[input.touchpad]
tap = true
"##,
        &format!(
            r#"version = 1

[input.touchpad]
pointer_accel = 0.3

[device."{TOUCHPAD}".input.touchpad]
tap = false
"#
        ),
    )
}

fn text(files: &[GeneratedFile], file: ConfigFile) -> String {
    let file = files.iter().find(|generated| generated.file() == file);
    file.unwrap().text()
}

#[test]
fn an_empty_state_generates_only_headers() {
    let (_dir, state) = state("", "");
    let files = generate(Registry::builtin(), &state, SWAY_1_10);
    assert_eq!(
        files.iter().map(GeneratedFile::file).collect::<Vec<_>>(),
        [
            ConfigFile::Input,
            ConfigFile::Appearance,
            ConfigFile::Behavior,
            ConfigFile::Effects
        ]
    );
    for file in files {
        assert!(file.is_empty());
        assert_eq!(file.text(), HEADER);
        assert!(file.text().starts_with("# Generated by Sway Things "));
    }
}

#[test]
fn every_file_is_generated_from_the_stored_settings() {
    let (_dir, state) = sample();
    let files = generate(Registry::builtin(), &state, SWAYFX_0_5);
    // In the order of the registry, the input types before the devices; the overlay wins.
    assert_eq!(
        text(&files, ConfigFile::Input),
        format!(
            "{HEADER}\
input type:touchpad tap enabled
input type:touchpad pointer_accel 0.3
input type:keyboard repeat_delay 300
input type:keyboard xkb_layout \"us,de\"
input \"{TOUCHPAD}\" tap disabled
"
        )
    );
    // One line for the two stored colors of `client.focused`, the others at their defaults.
    assert_eq!(
        text(&files, ConfigFile::Appearance),
        format!(
            "{HEADER}\
client.focused #4c7899 #285577 #eeeeee #2e9ef4 #3b6e4f
gaps inner 8
font \"Inter \\\"Display\\\" $$11\"
"
        )
    );
    assert_eq!(
        text(&files, ConfigFile::Behavior),
        format!(
            "{HEADER}\
focus_follows_mouse always
workspace_layout tabbed
"
        )
    );
    assert_eq!(
        text(&files, ConfigFile::Effects),
        format!("{HEADER}corner_radius 8\n")
    );
    assert!(files.iter().all(|file| !file.is_empty()));
    assert!(
        files
            .iter()
            .flat_map(GeneratedFile::lines)
            .all(|line| line.skipped.is_none())
    );
}

#[test]
fn the_same_state_generates_the_same_bytes() {
    let (_dir, first) = sample();
    let (_dir, second) = sample();
    let registry = Registry::builtin();
    assert_eq!(
        generate(registry, &first, SWAYFX_0_5),
        generate(registry, &second, SWAYFX_0_5)
    );
}

#[test]
fn what_the_compositor_does_not_support_becomes_a_comment() {
    let (_dir, state) = sample();
    let files = generate(Registry::builtin(), &state, SWAY_1_10);
    assert_eq!(
        text(&files, ConfigFile::Effects),
        format!("{HEADER}# effects.corner_radius: requires SwayFX 0.5 or newer\n")
    );
    let effects = &files[3];
    assert!(!effects.is_empty());
    assert_eq!(
        effects.lines()[0].skipped.as_deref(),
        Some("requires SwayFX 0.5 or newer")
    );
    // The other files are the same on sway and SwayFX.
    let on_swayfx = generate(Registry::builtin(), &state, SWAYFX_0_5);
    assert_eq!(files[..3], on_swayfx[..3]);
}

#[test]
fn a_value_the_builders_reject_becomes_a_comment() {
    let (_dir, state) = state(
        "[windows]\nfont = 'Inter\\11'\n[windows.gaps]\ninner = 4\n",
        &format!("[device.\"{TOUCHPAD}\".input.keyboard]\nxkb_layout = []\n"),
    );
    let files = generate(Registry::builtin(), &state, SWAY_1_10);
    assert_eq!(
        text(&files, ConfigFile::Appearance),
        format!(
            "{HEADER}\
gaps inner 4
# windows.font: backslash at byte 5
"
        )
    );
    assert_eq!(
        text(&files, ConfigFile::Input),
        format!(
            "{HEADER}# input.keyboard.xkb_layout (device {TOUCHPAD}): xkb_layout needs at least \
             one value\n"
        )
    );
}

#[test]
fn a_line_number_leads_back_to_its_settings() {
    let (_dir, state) = sample();
    let files = generate(Registry::builtin(), &state, SWAYFX_0_5);
    let source = |file: usize, line| files[file].source_of_line(line).cloned();
    let global = |keys: &[&'static str]| {
        Some(Source {
            keys: keys.to_vec(),
            device: None,
        })
    };
    // The header has two lines.
    assert_eq!(source(0, 0), None);
    assert_eq!(source(0, 1), None);
    assert_eq!(source(0, 2), None);
    assert_eq!(source(0, 3), global(&["input.touchpad.tap"]));
    assert_eq!(source(0, 6), global(&["input.keyboard.xkb_layout"]));
    assert_eq!(
        source(0, 7),
        Some(Source {
            keys: vec!["input.touchpad.tap"],
            device: Some(TOUCHPAD.to_owned())
        })
    );
    assert_eq!(source(0, 8), None);
    // Only the stored values of the directive, in the order of the registry.
    assert_eq!(
        source(1, 3),
        global(&["windows.focused.text", "windows.focused.child_border"])
    );
}
