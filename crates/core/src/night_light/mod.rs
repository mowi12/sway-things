/// How long the colors take to change at fixed times, in minutes: before the night ends and
/// after it starts.
const FADE_MINUTES: u32 = 30;

/// A night-light tool Sway Things can start.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Tool {
    /// wlsunset, preferred: arguments only.
    Wlsunset,
    /// gammastep, the successor of redshift.
    Gammastep,
}

impl Tool {
    /// Both, wlsunset first.
    pub const ALL: [Self; 2] = [Self::Wlsunset, Self::Gammastep];

    /// The name of its program, which is also the id of the choice and its package's name.
    pub const fn name(self) -> &'static str {
        match self {
            Self::Wlsunset => "wlsunset",
            Self::Gammastep => "gammastep",
        }
    }

    /// The tool of the choice `id`.
    pub fn from_id(id: &str) -> Option<Self> {
        Self::ALL.into_iter().find(|tool| tool.name() == id)
    }

    /// Where it is installed, if it is.
    pub fn find(self) -> Option<PathBuf> {
        find_program(self.name(), std::env::var_os("PATH").as_deref())
    }

    /// Whether it is installed.
    pub fn installed(self) -> bool {
        self.find().is_some()
    }
}

/// The tools that are installed, wlsunset first.
pub fn installed() -> Vec<Tool> {
    Tool::ALL
        .into_iter()
        .filter(|tool| tool.installed())
        .collect()
}

/// When the night light is on.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Schedule {
    /// From sunset to sunrise where the computer is.
    Sunset,
    /// From one time to another.
    Times,
    /// All the time, at the night temperature.
    Always,
}

impl Schedule {
    /// The schedule of the choice `id`; the default for anything else.
    pub fn from_id(id: &str) -> Self {
        match id {
            "times" => Self::Times,
            "always" => Self::Always,
            _ => Self::Sunset,
        }
    }
}

/// The settings of the night light in effect.
#[derive(Debug, Clone, PartialEq)]
pub struct Settings {
    /// Whether it is on.
    pub on: bool,
    /// The tool chosen.
    pub tool: Tool,
    /// When it is on.
    pub schedule: Schedule,
    /// The location entered by hand; `None` while it comes from the time zone.
    pub custom: Option<Coordinates>,
    /// When the night starts with fixed times, as hour and minute.
    pub from: (u32, u32),
    /// When the night ends with fixed times.
    pub to: (u32, u32),
    /// The temperature at night, in kelvin.
    pub night: u32,
    /// The temperature by day, in kelvin.
    pub day: u32,
}

/// The value of `key` in effect in `state`: the stored one, else the default.
fn value(state: &State, key: &str) -> Option<Value> {
    state.get(key, None).cloned().or_else(|| {
        Registry::builtin()
            .get(key)
            .map(crate::registry::Setting::default_value)
    })
}

impl Settings {
    /// The settings in effect in `state`.
    pub fn of(state: &State) -> Self {
        Self::read(|key| value(state, key))
    }

    /// The settings with the values `value` gives for the keys, the defaults where it gives
    /// none or a value of another type.
    pub fn read(value: impl Fn(&str) -> Option<Value>) -> Self {
        let default = |key: &str| {
            Registry::builtin()
                .get(key)
                .map(crate::registry::Setting::default_value)
        };
        let get = |key: &str| value(key).or_else(|| default(key));
        let text = |key: &str| match get(key) {
            Some(Value::Text(text) | Value::Choice(text)) => text,
            _ => String::new(),
        };
        let number = |key: &str| match get(key) {
            Some(Value::Decimal(number)) => number,
            #[expect(
                clippy::cast_precision_loss,
                reason = "the ranges of the settings are far below 2^52"
            )]
            Some(Value::Integer(number)) => number as f64,
            _ => 0.0,
        };
        let temperature = |key: &str, fallback: i64| {
            match get(key) {
                Some(Value::Integer(kelvin)) => kelvin,
                _ => fallback,
            }
            .clamp(MIN_TEMPERATURE, MAX_TEMPERATURE)
        };
        let kelvin = |value: i64| u32::try_from(value).unwrap_or(6500);
        let time = |key: &str, fallback: (u32, u32)| parse_time(&text(key)).unwrap_or(fallback);
        let custom = (text(LOCATION) == "custom").then(|| Coordinates {
            latitude: number(LATITUDE).clamp(-90.0, 90.0),
            longitude: number(LONGITUDE).clamp(-180.0, 180.0),
        });
        Self {
            on: get(ENABLED) == Some(Value::Bool(true)),
            tool: Tool::from_id(&text(TOOL)).unwrap_or(Tool::Wlsunset),
            schedule: Schedule::from_id(&text(SCHEDULE)),
            custom,
            from: time(FROM, (20, 0)),
            to: time(TO, (7, 0)),
            night: kelvin(temperature(TEMPERATURE_NIGHT, DEFAULT_NIGHT)),
            day: kelvin(temperature(TEMPERATURE_DAY, MAX_TEMPERATURE)),
        }
    }

    /// The tool to run of those `installed`: the one chosen, else the other one.
    pub fn tool_of(&self, installed: &[Tool]) -> Option<Tool> {
        if installed.contains(&self.tool) {
            Some(self.tool)
        } else {
            installed.first().copied()
        }
    }
}

/// Why the night light can't run as set.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum PlanError {
    /// From sunset to sunrise needs a location: the time zone (named, if known) has none in the
    /// database, as UTC.
    NoLocation(Option<String>),
    /// With fixed times, the night must start after it ends in the morning (20:00 to 07:00).
    TimesOrder,
}

impl PlanError {
    /// What is wrong, to show.
    pub fn text(&self) -> Text {
        match self {
            Self::NoLocation(Some(zone)) => Text::new(msg!(
                "The time zone {zone} has no place to take sunset and sunrise from: enter your \
                 location by hand, or use fixed times"
            ))
            .arg("zone", zone),
            Self::NoLocation(None) => Text::new(msg!(
                "The time zone isn't known, so sunset and sunrise can't be told: enter your \
                 location by hand, or use fixed times"
            )),
            Self::TimesOrder => Text::new(msg!(
                "The night must end before it starts again: the time it ends has to be earlier \
                 in the day than the time it starts, such as from 20:00 to 07:00"
            )),
        }
    }
}

/// How the tool is started: its arguments, and the config it reads (gammastep).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Plan {
    /// The tool.
    pub tool: Tool,
    /// Its arguments.
    pub args: Vec<OsString>,
    /// The text of the config file `args` names, for gammastep.
    pub config: Option<String>,
}

impl Plan {
    /// What tells this plan from another: a hash of the tool, the arguments and the config.
    pub fn fingerprint(&self) -> String {
        let mut hash = Sha256::new();
        hash.update(self.tool.name());
        for arg in &self.args {
            hash.update([0]);
            hash.update(arg.as_encoded_bytes());
        }
        if let Some(config) = &self.config {
            hash.update([0]);
            hash.update(config);
        }
        hash.finalize()
            .iter()
            .take(8)
            .fold(String::new(), |mut text, byte| {
                let _ = write!(text, "{byte:02x}");
                text
            })
    }
}

/// `HH:MM` of `minutes` after midnight.
fn clock(minutes: u32) -> String {
    format!("{:02}:{:02}", minutes / 60, minutes % 60)
}

/// The plan that starts `tool` as `settings` say: `zone` gives the location of the time zone,
/// needed only from sunset to sunrise without a location entered by hand; `config` is where
/// gammastep's config goes.
///
/// # Errors
///
/// [`PlanError::NoLocation`] without a location from sunset to sunrise,
/// [`PlanError::TimesOrder`] for fixed times where the night doesn't span midnight.
pub fn plan(
    settings: &Settings,
    tool: Tool,
    zone: impl FnOnce() -> Result<Coordinates, Option<String>>,
    config: &Path,
) -> Result<Plan, PlanError> {
    let night = settings.night;
    let minutes = |(hour, minute): (u32, u32)| hour * 60 + minute;
    // (end of the night, start of the night) in minutes; the temperatures by day and at night.
    let (times, temperatures, location) = match settings.schedule {
        Schedule::Sunset => {
            let location = match settings.custom {
                Some(custom) => custom,
                None => zone().map_err(PlanError::NoLocation)?,
            };
            (None, (settings.day.max(night), night), Some(location))
        }
        Schedule::Times => {
            let (end, start) = (minutes(settings.to), minutes(settings.from));
            if end >= start {
                return Err(PlanError::TimesOrder);
            }
            (Some((end, start)), (settings.day.max(night), night), None)
        }
        // The same temperature by day and at night, at any times.
        Schedule::Always => (Some((6 * 60, 18 * 60)), (night, night), None),
    };
    Ok(match tool {
        Tool::Wlsunset => {
            let (day, night) = temperatures;
            // wlsunset wants the day warmer than the night by at least one kelvin.
            let (low, high) = if day > night {
                (night, day)
            } else {
                (night.saturating_sub(1), night)
            };
            let mut args: Vec<String> = Vec::new();
            if let Some(location) = location {
                args.extend([
                    "-l".to_owned(),
                    format!("{:.4}", location.latitude),
                    "-L".to_owned(),
                    format!("{:.4}", location.longitude),
                ]);
            }
            if let Some((end, start)) = times {
                args.extend([
                    "-S".to_owned(),
                    clock(end),
                    "-s".to_owned(),
                    clock(start),
                    "-d".to_owned(),
                    (FADE_MINUTES * 60).to_string(),
                ]);
            }
            args.extend([
                "-t".to_owned(),
                low.to_string(),
                "-T".to_owned(),
                high.to_string(),
            ]);
            Plan {
                tool,
                args: args.into_iter().map(OsString::from).collect(),
                config: None,
            }
        }
        Tool::Gammastep => {
            let (day, night) = temperatures;
            let mut text = format!(
                "{HEADER}\n[general]\ntemp-day={day}\ntemp-night={night}\nfade=1\n\
                 adjustment-method=wayland\n"
            );
            if let Some((end, start)) = times {
                let _ = write!(
                    text,
                    "dawn-time={}-{}\ndusk-time={}-{}\n",
                    clock(end.saturating_sub(FADE_MINUTES)),
                    clock(end),
                    clock(start),
                    clock((start + FADE_MINUTES).min(23 * 60 + 59)),
                );
            }
            if let Some(location) = location {
                let _ = write!(
                    text,
                    "location-provider=manual\n\n[manual]\nlat={:.4}\nlon={:.4}\n",
                    location.latitude, location.longitude
                );
            }
            Plan {
                tool,
                args: vec![OsString::from("-c"), config.as_os_str().to_owned()],
                config: Some(text),
            }
        }
    })
}

/// The location of the time zone, or the name of the zone (if known) that has none.
///
/// # Errors
///
/// The name of the zone without a location, `None` if the zone isn't known.
pub fn zone_location() -> Result<Coordinates, Option<String>> {
    let zone = location::zone();
    zone.as_deref()
        .and_then(|zone| location::of_zone(zone, Path::new("/usr/share/zoneinfo")))
        .ok_or(zone)
}

/// Where Sway Things writes gammastep's config: `$XDG_CONFIG_HOME/sway-things/gammastep/
/// config.ini`. `None` without `HOME` or `XDG_CONFIG_HOME`.
pub fn config_path() -> Option<PathBuf> {
    let config_home = std::env::var_os("XDG_CONFIG_HOME")
        .map(PathBuf::from)
        .filter(|path| path.is_absolute())
        .or_else(|| std::env::var_os("HOME").map(|home| PathBuf::from(home).join(".config")))?;
    Some(config_home.join("sway-things/gammastep/config.ini"))
}

/// Writes `text` to `path`, unless a file is there that Sway Things didn't write (without
/// [`HEADER`]); nothing if it says that already.
///
/// # Errors
///
/// [`Problem::Foreign`] for a file of someone else's, [`Problem::Write`] if it can't be written.
pub fn write_config(path: &Path, text: &str) -> Result<(), Problem> {
    match std::fs::read_to_string(path) {
        Ok(old) if old == text => return Ok(()),
        Ok(old) if !old.starts_with(HEADER) => {
            return Err(Problem::Foreign(path.to_owned()));
        }
        Ok(_) => {}
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
        Err(error) => return Err(Problem::Write(path.to_owned(), error.to_string())),
    }
    crate::atomic::write(path, text)
        .map_err(|error| Problem::Write(path.to_owned(), error.to_string()))
}

/// The programs that change the colors of the displays, by the name the kernel gives their
/// process (at most 15 characters): a night light that runs.
const PROGRAMS: [&str; 7] = [
    "wlsunset",
    "gammastep",
    "gammastep-indic",
    "redshift",
    "wl-gammarelay-r",
    "wl-gammarelay",
    "sunsetr",
];

/// The programs an `exec` line of the user's config may start a night light with.
const LINE_PROGRAMS: [&str; 7] = [
    "wlsunset",
    "gammastep",
    "gammastep-indicator",
    "redshift",
    "wl-gammarelay-rs",
    "wl-gammarelay",
    "sunsetr",
];

/// A night light that runs and that Sway Things didn't start.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Foreign {
    /// Its program, as the kernel names its process.
    pub program: String,
    /// Its process number.
    pub pid: u32,
}

/// A night light of this session that Sway Things didn't start, if one runs.
pub fn foreign() -> Option<Foreign> {
    process::find_any(&PROGRAMS, MARKER)
        .into_iter()
        .find(|(_, found)| found.marker.is_none())
        .map(|(program, found)| Foreign {
            program,
            pid: found.pid,
        })
}

/// The tool Sway Things started that runs in this session, if one does.
pub fn running() -> Option<Tool> {
    Tool::ALL
        .into_iter()
        .find(|tool| !process::marked(tool.name(), MARKER).is_empty())
}

/// The `exec` and `exec_always` lines of `config` that start a night light: wlsunset,
/// gammastep (also its indicator), redshift, wl-gammarelay or sunsetr, also inside a shell
/// command. A line that runs Sway Things is ours.
pub fn own_lines(config: &SwayConfig) -> Vec<&Directive> {
    config
        .directives
        .iter()
        .filter(|directive| {
            directive.block.is_empty()
                && (directive.name.eq_ignore_ascii_case("exec")
                    || directive.name.eq_ignore_ascii_case("exec_always"))
        })
        .filter(|directive| {
            directive
                .args
                .iter()
                .flat_map(|arg| {
                    arg.split(|character: char| {
                        character.is_whitespace()
                            || matches!(character, ';' | '&' | '|' | '(' | ')')
                    })
                })
                .take_while(|word| word.rsplit('/').next() != Some("sway-things"))
                .any(|word| {
                    let word = word.trim_matches(|character| matches!(character, '"' | '\''));
                    let program = word.rsplit('/').next().unwrap_or(word);
                    LINE_PROGRAMS.contains(&program)
                })
        })
        .collect()
}

/// Why [`sync`] did nothing.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SyncError {
    /// No `XDG_RUNTIME_DIR` or no `WAYLAND_DISPLAY`: not in a session, so nothing is started or
    /// ended.
    NoSession,
    /// Another command kept the lock for longer than a few seconds.
    Busy,
}

impl SyncError {
    /// What is wrong, to show.
    pub fn text(self) -> Text {
        match self {
            Self::NoSession => Text::new(msg!(
                "Not in a sway session (XDG_RUNTIME_DIR or WAYLAND_DISPLAY isn't set), so the \
                 night light is neither started nor ended"
            )),
            Self::Busy => Text::new(msg!(
                "Another command of Sway Things is starting the night light"
            )),
        }
    }
}

/// Why the night light that is on doesn't run.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Problem {
    /// Neither wlsunset nor gammastep is installed.
    NoTool,
    /// It can't run as set.
    Plan(PlanError),
    /// gammastep's config is there, but Sway Things didn't write it.
    Foreign(PathBuf),
    /// gammastep's config can't be written.
    Write(PathBuf, String),
    /// The tool ended at once; the last line it wrote says why.
    Ended(Tool, String),
}

impl Problem {
    /// What is wrong, to show.
    pub fn text(&self) -> Text {
        match self {
            Self::NoTool => Text::new(msg!(
                "Neither wlsunset nor gammastep is installed; install one of them"
            )),
            Self::Plan(error) => error.text(),
            Self::Foreign(path) => Text::new(msg!(
                "{file} wasn't written by Sway Things, so it is left alone and gammastep isn't \
                 started"
            ))
            .arg("file", path.display()),
            Self::Write(path, error) => Text::new(msg!("{file} can't be written: {error}"))
                .arg("file", path.display())
                .arg("error", error),
            Self::Ended(tool, said) if said.is_empty() => {
                Text::new(msg!("{tool} ended right after it started")).arg("tool", tool.name())
            }
            Self::Ended(tool, said) => {
                Text::new(msg!("{tool} ended right after it started: {error}"))
                    .arg("tool", tool.name())
                    .arg("error", said)
            }
        }
    }
}

/// What [`sync`] did.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct Synced {
    /// How many tools of Sway Things were ended.
    pub ended: usize,
    /// The tool started, if one was.
    pub started: Option<Tool>,
    /// Whether the tool that runs already was kept, as it runs as set.
    pub kept: bool,
    /// A night light of the user's own that runs; then Sway Things runs none.
    pub foreign: Option<Foreign>,
    /// Why the night light that is on doesn't run.
    pub problem: Option<Problem>,
}

/// [`sync_with`] for the settings of `state`; `external` says whether the user's config starts a
/// night light ([`own_lines`]).
///
/// # Errors
///
/// Those of [`sync_with`].
pub fn sync(state: &State, external: bool) -> Result<Synced, SyncError> {
    let settings = Settings::of(state);
    sync_with(|| settings, external)
}

/// The log of the tool's standard error, for the reason it ended.
fn log_path() -> Option<PathBuf> {
    std::env::var_os("XDG_RUNTIME_DIR")
        .filter(|dir| !dir.is_empty())
        .map(|dir| PathBuf::from(dir).join("sway-things-night-light.log"))
}

/// Has exactly the night light run that the settings ask for: none while it is off, while the
/// user's config starts one (`external`) or one of the user's own runs, without a tool or while
/// it can't run as set; else the chosen tool (or the other one, if only that is installed) as
/// set. Ends the others Sway Things started in this session and waits for them to end, since
/// gammastep keeps the colors for a moment while it fades back. `settings` is read once the lock
/// is held, so of the hook and the app running at once the second acts on what is set by then.
///
/// # Errors
///
/// [`SyncError::NoSession`] outside a sway session, [`SyncError::Busy`] if the lock stays held
/// for five seconds.
pub fn sync_with(settings: impl FnOnce() -> Settings, external: bool) -> Result<Synced, SyncError> {
    let in_session = ["XDG_RUNTIME_DIR", "WAYLAND_DISPLAY"]
        .iter()
        .all(|variable| std::env::var_os(variable).is_some_and(|value| !value.is_empty()));
    if !in_session {
        return Err(SyncError::NoSession);
    }
    let _lock = Lock::wait(LOCK, Duration::from_secs(5)).map_err(|error| match error {
        LockError::NoRuntimeDir => SyncError::NoSession,
        LockError::Busy => SyncError::Busy,
    })?;
    let settings = settings();
    let ours: Vec<(Tool, process::Found)> = Tool::ALL
        .into_iter()
        .flat_map(|tool| {
            process::marked(tool.name(), MARKER)
                .into_iter()
                .map(move |found| (tool, found))
        })
        .collect();
    let mut synced = Synced {
        foreign: foreign(),
        ..Synced::default()
    };
    let wanted = if !settings.on || external || synced.foreign.is_some() {
        None
    } else {
        match wanted_plan(&settings) {
            Ok(plan) => Some(plan),
            Err(problem) => {
                synced.problem = Some(problem);
                None
            }
        }
    };
    let fingerprint = wanted.as_ref().map(Plan::fingerprint);
    let mut unwanted = Vec::new();
    for (tool, found) in ours {
        let same = wanted.as_ref().is_some_and(|plan| plan.tool == tool)
            && found.marker.as_deref() == fingerprint.as_deref();
        if same && !synced.kept {
            synced.kept = true;
        } else {
            unwanted.push(found.pid);
        }
    }
    end(&unwanted);
    synced.ended = unwanted.len();
    if let (Some(plan), Some(fingerprint), false) = (wanted, fingerprint, synced.kept) {
        match start(&plan, &fingerprint) {
            Ok(()) => synced.started = Some(plan.tool),
            Err(problem) => synced.problem = Some(problem),
        }
    }
    Ok(synced)
}

/// The plan for `settings` with the tools that are installed, and gammastep's config written.
fn wanted_plan(settings: &Settings) -> Result<Plan, Problem> {
    let tool = settings.tool_of(&installed()).ok_or(Problem::NoTool)?;
    let config = config_path().unwrap_or_else(|| PathBuf::from("config.ini"));
    let plan = plan(settings, tool, zone_location, &config).map_err(Problem::Plan)?;
    if let Some(text) = &plan.config {
        write_config(&config, text)?;
    }
    Ok(plan)
}

/// Ends the processes `pids` and waits up to three seconds for them, then kills those left.
fn end(pids: &[u32]) {
    if pids.is_empty() {
        return;
    }
    process::signal(pids, "TERM");
    let start = Instant::now();
    while pids.iter().any(|pid| process::runs(*pid)) && start.elapsed() < Duration::from_secs(3) {
        std::thread::sleep(Duration::from_millis(50));
    }
    let left: Vec<u32> = pids
        .iter()
        .copied()
        .filter(|pid| process::runs(*pid))
        .collect();
    process::signal(&left, "KILL");
}

/// Starts the tool of `plan` detached, marked with `fingerprint`, and checks a moment later that
/// it still runs.
fn start(plan: &Plan, fingerprint: &str) -> Result<(), Problem> {
    let path = plan.tool.find().ok_or(Problem::NoTool)?;
    let log = log_path();
    let stderr = log
        .as_ref()
        .and_then(|log| std::fs::File::create(log).ok())
        .map_or_else(Stdio::null, Stdio::from);
    let started = Command::new("setsid")
        .arg("-f")
        .arg(path)
        .args(&plan.args)
        .env(MARKER, fingerprint)
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(stderr)
        .status()
        .is_ok_and(|status| status.success());
    let ended = |said: String| Problem::Ended(plan.tool, said);
    if !started {
        return Err(ended(String::new()));
    }
    std::thread::sleep(Duration::from_millis(500));
    if process::marked(plan.tool.name(), MARKER).is_empty() {
        let said = log
            .and_then(|log| std::fs::read_to_string(log).ok())
            .and_then(|text| {
                text.lines()
                    .map(str::trim)
                    .rfind(|line| !line.is_empty())
                    .map(ToOwned::to_owned)
            })
            .unwrap_or_default();
        return Err(ended(said));
    }
    Ok(())
}

