//! The night light: warmer colors in the evening, made by wlsunset or gammastep.
//!
//! sway can't change the colors of the displays itself; a tool does it over the
//! `wlr-gamma-control` protocol, and only one at a time can. Sway Things starts the user's tool
//! detached for the session (`setsid -f`, like the clipboard history's watcher), with
//! `SWAY_THINGS_NIGHT_LIGHT=<fingerprint of its arguments>` in its environment:
//! `sway-things hook night-light`, which `80-hooks.conf` runs at every start and reload of sway
//! while the night light is on, and the app and the command line when a setting changes. [`sync`]
//! makes it so that exactly the tool the settings ask for runs, so running it twice changes
//! nothing; a new setting ends the old one and starts it again.
//!
//! - **wlsunset** takes everything as arguments ([`Plan::args`]).
//! - **gammastep** takes the fixed times only from a config file, so it gets ours,
//!   `$XDG_CONFIG_HOME/sway-things/gammastep/config.ini`, with `-c` ([`Plan::config`]), which
//!   also keeps the user's own `config.ini` out of it.
//!
//! A tool the user starts (a line of their config, a systemd unit, gammastep-indicator) is never
//! ended, and while one runs or the config starts one, Sway Things starts none.

