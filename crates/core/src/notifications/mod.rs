/// The first line of every file Sway Things writes for a notification daemon (and, as a
/// `$comment`, the first member of swaync's `config.json`). A file that starts with it was
/// written by Sway Things.
pub const HEADER: &str =
    "Generated by Sway Things from ~/.config/sway-things/settings.toml. DO NOT EDIT.";

/// A notification daemon.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Daemon {
    /// mako
    Mako,
    /// `SwayNotificationCenter`
    Swaync,
    /// dunst
    Dunst,
    /// Another one (fnott, a desktop's own, …).
    Other,
}

impl Daemon {
    /// The daemons Sway Things knows.
    pub const KNOWN: [Self; 3] = [Self::Mako, Self::Swaync, Self::Dunst];

    /// The daemon behind the name `GetServerInformation` gives.
    pub fn from_server_name(name: &str) -> Self {
        match name {
            "mako" => Self::Mako,
            "SwayNotificationCenter" | "swaync" => Self::Swaync,
            "dunst" => Self::Dunst,
            _ => Self::Other,
        }
    }

    /// The program, which is also the id of `notifications.start`.
    pub const fn program(self) -> &'static str {
        match self {
            Self::Mako => "mako",
            Self::Swaync => "swaync",
            Self::Dunst => "dunst",
            Self::Other => "",
        }
    }

    /// The daemon of a `notifications.start` id.
    pub fn from_program(program: &str) -> Option<Self> {
        Self::KNOWN
            .into_iter()
            .find(|daemon| daemon.program() == program)
    }

    /// The name to show.
    pub const fn title(self) -> &'static str {
        match self {
            Self::Mako => "mako",
            Self::Swaync => "SwayNotificationCenter",
            Self::Dunst => "dunst",
            Self::Other => "",
        }
    }

    /// Whether it is installed: an executable of its name in `$PATH`.
    pub fn installed(self) -> bool {
        self != Self::Other
            && crate::delegate::find_program(self.program(), std::env::var_os("PATH").as_deref())
                .is_some()
    }
}

/// The stored values of the Notifications page, for the generators: a value that isn't stored
/// is the daemon's own, so it isn't written.
#[derive(Debug, Clone, Copy)]
pub struct Stored<'a> {
    state: &'a State,
}

impl<'a> Stored<'a> {
    /// The values stored in `state`.
    pub fn new(state: &'a State) -> Self {
        Self { state }
    }

    /// The stored value of `key`.
    pub fn get(&self, key: &str) -> Option<&'a Value> {
        self.state.get(key, None)
    }

    /// The stored whole number of `key`.
    pub fn integer(&self, key: &str) -> Option<i64> {
        match self.get(key) {
            Some(Value::Integer(value)) => Some(*value),
            _ => None,
        }
    }

    /// The stored on/off value of `key`.
    pub fn bool(&self, key: &str) -> Option<bool> {
        match self.get(key) {
            Some(Value::Bool(value)) => Some(*value),
            _ => None,
        }
    }

    /// The stored text or choice of `key`.
    pub fn text(&self, key: &str) -> Option<&'a str> {
        match self.get(key) {
            Some(Value::Text(value) | Value::Choice(value)) => Some(value),
            _ => None,
        }
    }

    /// The stored list of `key`.
    pub fn list(&self, key: &str) -> Option<&'a [String]> {
        match self.get(key) {
            Some(Value::List(value)) => Some(value),
            _ => None,
        }
    }

    /// The value of `key` in effect: stored, else the default.
    pub fn effective(&self, key: &str) -> Option<Value> {
        self.get(key).cloned().or_else(|| {
            Registry::builtin()
                .get(key)
                .map(registry::Setting::default_value)
        })
    }

    /// The color of `key` in effect.
    fn color(self, key: &str) -> Option<Color> {
        match self.effective(key) {
            Some(Value::Color(color)) => Some(color),
            _ => None,
        }
    }

    /// The colors to write, or `None` for the daemon's own: those of the focused window
    /// (background, text, and its border as the accent), or the custom ones.
    pub fn colors(&self) -> Option<Colors> {
        match self.text(keys::COLORS)? {
            "windows" => Some(Colors {
                background: self.color("windows.focused.background")?,
                text: self.color("windows.focused.text")?,
                border: self.color("windows.focused.child_border")?,
            }),
            "custom" => Some(Colors {
                background: self.color(keys::BACKGROUND)?,
                text: self.color(keys::TEXT)?,
                border: self.color(keys::BORDER)?,
            }),
            _ => None,
        }
    }
}

/// The colors of notifications.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Colors {
    /// The background.
    pub background: Color,
    /// The text.
    pub text: Color,
    /// The border, also the accent.
    pub border: Color,
}

/// The line of the generated config that starts the daemon chosen to start with sway:
/// `exec_always sway-things hook notification-daemon`. The hook starts it with an argument list
/// (swaync with our files, `-c` and `-s`), unless a daemon runs already, so a reload of sway
/// also starts one that ended.
pub fn start_line() -> SwayCmd {
    crate::command::hook("notification-daemon")
}

/// The command that has sway run the hook once, now (over IPC).
pub fn start_now() -> SwayCmd {
    SwayCmd::new("exec")
        .keyword("sway-things")
        .keyword("hook")
        .keyword("notification-daemon")
}

/// Starts `daemon` as a process of its own and returns at once: sway's `exec` would read paths
/// through a shell. swaync gets our files with `-c` and `-s` while `ours` is true, else runs with
/// its own config. Its output goes where ours does (sway's log). Its process id goes to
/// [`pid_file`], so that a daemon our hook started can be told from one the user started.
///
/// # Errors
///
/// If it can't be started, e.g. isn't installed; [`std::io::ErrorKind::Unsupported`] for
/// [`Daemon::Other`].
#[allow(
    clippy::zombie_processes,
    reason = "the daemon outlives the hook, which ends right after starting it"
)]
pub fn spawn(daemon: Daemon, files: &files::Files, ours: bool) -> std::io::Result<()> {
    use std::os::unix::process::CommandExt as _;
    let mut command = std::process::Command::new(daemon.program());
    match daemon {
        Daemon::Swaync if ours => {
            command
                .arg("-c")
                .arg(&files.swaync_config)
                .arg("-s")
                .arg(&files.swaync_style);
        }
        Daemon::Swaync | Daemon::Mako | Daemon::Dunst => {}
        Daemon::Other => return Err(std::io::ErrorKind::Unsupported.into()),
    }
    let child = command
        .stdin(std::process::Stdio::null())
        .process_group(0)
        .spawn()?;
    if let Some(path) = pid_file() {
        if let Some(dir) = path.parent() {
            let _ = std::fs::create_dir_all(dir);
        }
        let _ = crate::atomic::write(&path, &format!("{}\n", child.id()));
    }
    Ok(())
}

/// Where the hook notes the process id of the daemon it started:
/// `$XDG_RUNTIME_DIR/sway-things/notification-daemon.pid`, which goes away with the session.
pub fn pid_file() -> Option<std::path::PathBuf> {
    let runtime = std::env::var_os("XDG_RUNTIME_DIR")
        .map(std::path::PathBuf::from)
        .filter(|path| path.is_absolute())?;
    Some(runtime.join("sway-things/notification-daemon.pid"))
}

/// Whether the process `pid` is the daemon our hook started ([`pid_file`]).
pub fn started_by_us(pid: u32) -> bool {
    pid_file()
        .and_then(|path| std::fs::read_to_string(path).ok())
        .is_some_and(|text| text.trim().parse::<u32>().ok() == Some(pid))
}
