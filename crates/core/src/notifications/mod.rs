//! The notification daemon: which one runs and what starts it ([`bus`], [`starts`]), Do Not
//! Disturb, and the files Sway Things writes for it, each in the daemon's own format.
//!
//! - **mako** reads our file `$XDG_CONFIG_HOME/mako/sway-things` ([`mako::generate`]) through an
//!   `include=` line in its config. Without a mako config at all, one is created that only
//!   includes ours ([`files::Files::write_mako`]).
//! - **swaync** has no include: Sway Things writes a complete `config.json` and `style.css` of
//!   its own to `$XDG_CONFIG_HOME/sway-things/swaync/` ([`swaync`]), and swaync is started with
//!   `-c` and `-s` naming them (a handover).
//! - **dunst** is only asked and switched (Do Not Disturb); nothing is written for it yet.
//!
//! The user's own files are only ever read.

